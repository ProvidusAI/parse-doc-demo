const STRINGS: Record<UiLang, Record<UiKey, string>> = { en, ar };

export function t(lang: UiLang, key: UiKey, vars: Record<string, string | number> = {}): string {
  return STRINGS[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

